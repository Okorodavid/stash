"""Regenerate app/src/lib/abis.ts from Foundry build output.

Usage (from repo root, after `forge build` in contracts/):
    python scripts/gen-abis.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    "stashFactoryAbi": ROOT / "contracts/out/StashFactory.sol/StashFactory.json",
    "stashVaultAbi": ROOT / "contracts/out/StashVault.sol/StashVault.json",
}
ERC20 = """export const erc20Abi = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "spender", type: "address" }, { name: "amount", type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "owner", type: "address" }, { name: "spender", type: "address" }], outputs: [{ type: "uint256" }] },
] as const;
"""

lines = ["// Generated by scripts/gen-abis.py from contracts/out. Re-run after changing the contracts.", ""]
for name, path in SOURCES.items():
    abi = json.loads(path.read_text(encoding="utf-8"))["abi"]
    lines += [f"export const {name} = {json.dumps(abi)} as const;", ""]
out = ROOT / "app/src/lib/abis.ts"
out.write_text("\n".join(lines) + ERC20, encoding="utf-8")
print(f"wrote {out}")
